"""Landmarks for the "Hands off" twist: castles, churches, chapels, monuments and viewpoints near each mission.

    uv run --with pyproj python pipeline/build_landmarks.py   # writes src/core/data/landmarks.ts

OSM (Overpass, cached in pipeline/cache/landmarks-<region>.json): named
  historic = castle | manor | fort | monument | church | chapel, building = church | chapel | cathedral,
  amenity = place_of_worship (named), tourism = viewpoint (named or not).
Each becomes one point (a node, or a way's / relation's centre) in EPSG:5514 (the packs' crs), rounded to 1 m.
Small kinds: wayside crosses, memorial plaques and shrines are not landmarks (historic = wayside_cross | memorial |
wayside_shrine are not queried). Bunkers of the 1930s border line on the D11 map are `historic=fort` (OSM tags
the Czechoslovak fortification objects so, e.g. Stachelberg). The game decides per mission which are near enough
to matter (data/twists.ts).
"""
from __future__ import annotations

import json
import time
import urllib.parse
import urllib.request
from pathlib import Path

from pyproj import Transformer

ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / "pipeline" / "cache"
OUT = ROOT / "src" / "core" / "data" / "landmarks.ts"
# (south, west, north, east): the packs' boxes, widened a little (pipeline/scenarios/*.json)
REGIONS = {
    "d11": (50.485, 15.825, 50.712, 16.045),
    "d3": (49.505, 14.43, 49.995, 14.675),
    "d35": (49.71, 16.46, 49.86, 16.935),
    "i46": (49.668, 17.255, 49.757, 17.352),
    "i35": (50.401, 15.084, 50.644, 15.471),
}
QUERY = """[out:json][timeout:120][bbox:{s},{w},{n},{e}];
(
  nwr[historic~"^(castle|manor|fort|monument|church|chapel)$"];
  nwr[building~"^(church|chapel|cathedral)$"];
  nwr[amenity=place_of_worship][name];
  nwr[tourism=viewpoint];
);
out center tags qt;"""
SERVERS = ["https://overpass.kumi.systems/api/interpreter", "https://overpass-api.de/api/interpreter",
           "https://maps.mail.ru/osm/tools/overpass/api/interpreter"]


def fetch(region: str, box) -> dict:
    path = CACHE / f"landmarks-{region}.json"
    if path.exists():
        return json.loads(path.read_text())
    s, w, n, e = box
    body = urllib.parse.urlencode({"data": QUERY.format(s=s, w=w, n=n, e=e)}).encode()
    last = None
    for server in SERVERS:
        try:
            with urllib.request.urlopen(urllib.request.Request(server, body, {"User-Agent": "trapla-landmarks"}), timeout=180) as r:
                data = json.loads(r.read())
            if "remark" in data and "error" in data["remark"].lower():
                raise RuntimeError(data["remark"])
            path.write_text(json.dumps(data))
            return data
        except Exception as ex:  # noqa: BLE001 - try the next mirror
            last = ex
            time.sleep(2)
    raise RuntimeError(f"{region}: no Overpass server answered ({last})")


def kind(tags: dict) -> str | None:
    h, b = tags.get("historic", ""), tags.get("building", "")
    if h in ("castle", "manor"):
        return "castle"
    if h == "fort":
        return "monument"
    if h == "monument":
        return "monument"
    if tags.get("tourism") == "viewpoint":
        return "viewpoint"
    if b == "chapel" or h == "chapel":
        return "chapel"
    if b in ("church", "cathedral") or h == "church":
        return "church"
    if tags.get("amenity") == "place_of_worship":
        # a named place of worship that is not tagged as a building of its own: a chapel unless it says church
        return "church" if "kostel" in tags.get("name", "").lower() else "chapel"
    return None


def main():
    to5514 = Transformer.from_crs("EPSG:4326", "EPSG:5514", always_xy=True)
    out = []
    for region, box in REGIONS.items():
        data = fetch(region, box)
        seen = set()
        for el in data["elements"]:
            tags = el.get("tags", {})
            k = kind(tags)
            if not k:
                continue
            lat, lon = (el["lat"], el["lon"]) if el["type"] == "node" else (el["center"]["lat"], el["center"]["lon"])
            x, y = to5514.transform(lon, lat)
            name = tags.get("name") or tags.get("name:cs") or ""
            if not name:  # an unnamed viewpoint is mostly a bench by a path, not a landmark
                continue
            key = (k, name, round(x / 30), round(y / 30))
            if key in seen:  # a church mapped as a node and as its building
                continue
            seen.add(key)
            out.append({"name": name, "kind": k, "x": round(x), "y": round(y), "osm": f"{el['type']}/{el['id']}"})
    out.sort(key=lambda l: (l["x"], l["y"]))
    rows = ",\n".join(f"  [{json.dumps(l['name'], ensure_ascii=False)}, '{l['kind']}', {l['x']}, {l['y']}, '{l['osm']}']" for l in out)
    OUT.write_text("// Generated by pipeline/build_landmarks.py from OpenStreetMap (© OpenStreetMap contributors, ODbL): name, kind,\n"
                   "// EPSG:5514 x, y (m), OSM object. Do not edit by hand.\n"
                   "export type LandmarkKind = 'castle' | 'church' | 'chapel' | 'monument' | 'viewpoint';\n"
                   f"export const LANDMARKS: readonly (readonly [string, LandmarkKind, number, number, string])[] = [\n{rows},\n];\n")
    print(f"{len(out)} landmarks → {OUT}")


if __name__ == "__main__":
    main()
